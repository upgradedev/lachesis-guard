"""Prints src/acme_catalog/domain/vat_rates.py, generated from data/vat_rates.csv.

    python scripts/gen_vat_rates.py > src/acme_catalog/domain/vat_rates.py
"""
from __future__ import annotations

import csv
import sys
from decimal import Decimal
from pathlib import Path

CSV_PATH = Path(__file__).resolve().parents[1] / "data" / "vat_rates.csv"

HEADER = '''"""VAT rates by country. Generated by scripts/gen_vat_rates.py from data/vat_rates.csv: do not edit."""
from decimal import Decimal

from acme_catalog.infrastructure.rate_cache import memoised

'''

FOOTER = '''

class UnknownCountry(KeyError):
    pass


@memoised
def rate_for(country_code: str) -> Decimal:
    try:
        return RATES[country_code.upper()]
    except KeyError:
        raise UnknownCountry(country_code) from None
'''


def read_rates(path: Path = CSV_PATH):
    with path.open(newline="", encoding="utf-8") as handle:
        rows = [(row["country_code"].strip().upper(), Decimal(row["rate"].strip())) for row in csv.DictReader(handle)]
    return sorted(rows)


def render(rows) -> str:
    body = "RATES = {\n" + "".join(f'    "{code}": Decimal("{rate}"),\n' for code, rate in rows) + "}\n"
    return HEADER + body + FOOTER


if __name__ == "__main__":
    sys.stdout.write(render(read_rates()))
