"""The console's explorer, simulator and metrics data must be the committed rows.

approvals/console/data.js is generated by scripts/build_console_data.py; this
test regenerates it and fails on any difference, so a hand edit or a stale
file cannot reach the judged console. The generator itself asserts the
figures the 2026-10-19 verification recomputed from the same rows.
"""

from __future__ import annotations

import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONSOLE = ROOT / "approvals" / "console"


def _generator():
    spec = importlib.util.spec_from_file_location(
        "build_console_data", ROOT / "scripts" / "build_console_data.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_console_data_is_generated_from_the_rows():
    gen = _generator()
    expected = gen.render(gen.build())
    actual = (CONSOLE / "data.js").read_text(encoding="utf-8")
    assert actual == expected, "data.js is stale: run python scripts/build_console_data.py"


def test_console_reads_only_the_generated_data():
    html = (CONSOLE / "index.html").read_text(encoding="utf-8")
    js = (CONSOLE / "app.js").read_text(encoding="utf-8")
    assert html.index('src="data.js') < html.index('src="app.js')
    assert "window.LACHESIS_DATA" in js
    for invented in (
        "triage_results_2026-10-16",
        "sagemaker_probe_2026-10-16_g4dn",
        "const CASES",
        "THR_SIM",
    ):
        assert invented not in js and invented not in html, invented
    # Every cited rows file exists.
    for name in (
        "threshold_cases.jsonl",
        "gpu_threshold_2026-10-13.jsonl",
        "sagemaker_g4dn_2026-10-16.jsonl",
        "baseline_2026-10-13.jsonl",
        "expanded_cases.jsonl",
        "expanded_cpu_2026-10-16.jsonl",
    ):
        assert name in js and (ROOT / "evaluation" / name).exists(), name


def test_console_data_rows_match_their_sources():
    text = (CONSOLE / "data.js").read_text(encoding="utf-8")
    data = json.loads(text[text.index("{") : text.rstrip().rindex(";")])
    assert len(data["set50"]) == 50 and len(data["expanded"]) == 128
    t31 = next(c for c in data["set50"] if c["id"] == "t31")
    assert t31["tool"] == "s3_upload" and t31["at"]["0.70"] == ["R1", "Pause"]
    d021 = next(c for c in data["expanded"] if c["id"] == "d021")
    assert d021["conf"] == 0.827 and d021["target"] == "refunds_prod_config.py"
    assert data["baseline"]["sdk_ran"] == ["t19", "t22", "t25"]
